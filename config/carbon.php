<?php

return [
    /*
    |--------------------------------------------------------------------------
    | 本地化语言
    |--------------------------------------------------------------------------
    | 用于 Carbon 的日期时间文案，例如 diffForHumans() 输出的“3 分钟前”。
    | 默认 zh_CN，对应 Carbon 内置的中文简体语言包。可填写 en、zh_TW、
    | zh_Hans 等 Carbon 支持的语言标识，也兼容 zh-cn 这种带短横线的写法。
    | 留空表示不修改 Carbon 的当前语言。
    */
    'locale' => 'zh_CN',

    /*
    |--------------------------------------------------------------------------
    | 回退语言
    |--------------------------------------------------------------------------
    | 当 locale 对应的语言包缺少某条翻译时，使用该语言兜底。
    | 默认 en，即 Carbon 的内置英文文案。留空表示不设置回退语言。
    */
    'fallback_locale' => 'en',

    /*
    |--------------------------------------------------------------------------
    | 时区
    |--------------------------------------------------------------------------
    | 门面、助手函数和容器创建的 Carbon 实例统一使用的时区，例如
    | Asia/Shanghai。留空（null）表示跟随 ThinkPHP 的 app.default_timezone，
    | 该配置会在应用初始化时写入 PHP 默认时区，Carbon 会自动继承。
    | 注意：此配置不会修改全局 PHP 时区，只影响本包创建的实例。
    */
    'timezone' => null,
];